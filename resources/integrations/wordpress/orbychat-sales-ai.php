    public function inject_widget_script() {
        $options = get_option($this->option_name);
        if (empty($options['api_url']) || empty($options['agent_id'])) {
            return;
        }

        $url = rtrim($options['api_url'], '/') . '/widget/widget.js';
        $agent_id = esc_attr($options['agent_id']);

        echo "\n<!-- OrbyChat Sales AI Widget -->\n";
        echo "<script async src='{$url}' data-agent-id='{$agent_id}'></script>\n";
    }

    public function handle_sync_ajax() {
        check_ajax_referer('orbychat_sync');

        if (!current_user_can('manage_options')) {
            wp_send_json_error(__('Unauthorized', 'orbychat-sales-ai'));
        }

        $options = get_option($this->option_name);
        if (empty($options['api_url']) || empty($options['api_token'])) {
            wp_send_json_error(__('API settings not configured', 'orbychat-sales-ai'));
        }

        $items = array();
        
        // 1. Collect Products
        if (class_exists('WooCommerce')) {
            $wc_products = wc_get_products(array('status' => 'publish', 'limit' => -1));
            foreach ($wc_products as $product) {
                $items[] = array(
                    'external_id' => 'wc_' . $product->get_id(),
                    'type' => 'product',
                    'title' => $product->get_name(),
                    'url' => get_permalink($product->get_id()),
                    'body' => strip_tags($product->get_description() . ' ' . $product->get_short_description()),
                    'price' => $product->get_price(),
                    'currency' => get_woocommerce_currency(),
                    'image_url' => wp_get_attachment_url($product->get_image_id()),
                    'in_stock' => $product->is_in_stock(),
                );
            }
        }

        // 2. Collect Pages & Posts
        $posts = get_posts(array('post_type' => array('page', 'post'), 'post_status' => 'publish', 'numberposts' => -1));
        foreach ($posts as $post) {
            $items[] = array(
                'external_id' => 'wp_' . $post->ID,
                'type' => 'page',
                'title' => $post->post_title,
                'url' => get_permalink($post->ID),
                'body' => strip_shortcodes(strip_tags($post->post_content)),
            );
        }

        // 3. Post to OrbyChat
        $response = wp_remote_post(rtrim($options['api_url'], '/') . '/api/v1/integrations/wordpress/sync', array(
            'headers' => array(
                'X-OrbyChat-Token' => $options['api_token'],
                'Content-Type' => 'application/json',
            ),
            'body' => json_encode(array(
                'agent_id' => $options['agent_id'],
                'items' => $items,
            )),
            'timeout' => 60,
        ));

        if (is_wp_error($response)) {
            wp_send_json_error($response->get_error_message());
        }

        $body = json_decode(wp_remote_retrieve_body($response), true);
        if (wp_remote_retrieve_response_code($response) !== 200) {
            wp_send_json_error($body['message'] ?? __('Failed to sync with OrbyChat.', 'orbychat-sales-ai'));
        }

        wp_send_json_success(array('count' => count($items)));
    }

    public function track_cart_event() {
        if (!function_exists('WC') || !WC()->cart) return;

        $cart = WC()->cart;
        $data = array(
            'event' => 'cart_updated',
            'cart_total' => $cart->get_total('raw'),
            'currency' => get_woocommerce_currency(),
            'items' => array()
        );

        foreach ($cart->get_cart() as $item) {
            $data['items'][] = array(
                'id' => $item['product_id'],
                'name' => get_the_title($item['product_id']),
                'quantity' => $item['quantity'],
                'price' => $item['data']->get_price()
            );
        }

        $this->push_to_orbychat('events/cart', $data);
    }

    public function track_order_completed($order_id) {
        $order = wc_get_order($order_id);
        if (!$order) return;

        $data = array(
            'event' => 'order_completed',
            'order_id' => $order_id,
            'total' => $order->get_total(),
            'currency' => $order->get_currency(),
            'email' => $order->get_billing_email()
        );

        $this->push_to_orbychat('events/order', $data);
    }

    private function push_to_orbychat($endpoint, $data) {
        $options = get_option($this->option_name);
        $token = isset($options['api_token']) ? $options['api_token'] : '';
        if (empty($token) || empty($options['api_url'])) return;

        wp_remote_post(rtrim($options['api_url'], '/') . '/api/v1/integrations/wordpress/' . $endpoint, array(
            'headers' => array(
                'X-OrbyChat-Token' => $token,
                'Content-Type'     => 'application/json',
            ),
            'body' => json_encode($data),
            'blocking' => false,
        ));
    }
