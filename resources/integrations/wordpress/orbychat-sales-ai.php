    public function register_rest_routes() {
        register_rest_route('orbychat/v1', '/coupons/apply', array(
            'methods' => 'POST',
            'callback' => array($this, 'rest_apply_coupon'),
            'permission_callback' => array($this, 'validate_api_token'),
        ));

        register_rest_route('orbychat/v1', '/orders/(?P<id>\d+)', array(
            'methods' => 'GET',
            'callback' => array($this, 'rest_get_order'),
            'permission_callback' => array($this, 'validate_api_token'),
        ));
    }

    public function validate_api_token(WP_REST_Request $request) {
        $token = $request->get_header('X-OrbyChat-Token');
        $options = get_option($this->option_name);
        $saved_token = isset($options['api_token']) ? $options['api_token'] : '';
        return !empty($token) && hash_equals($saved_token, $token);
    }

    public function rest_apply_coupon(WP_REST_Request $request) {
        if (!class_exists('WooCommerce')) {
            return new WP_Error('no_wc', __('WooCommerce is not active on this site.', 'orbychat-sales-ai'), array('status' => 400));
        }

        $params = $request->get_json_params();
        $max_discount = isset($params['max_discount']) ? intval($params['max_discount']) : 10;
        
        // Generate a unique, professional coupon code
        $coupon_code = strtoupper('ORBY-' . wp_generate_password(6, false));
        
        try {
            $coupon = new WC_Coupon();
            $coupon->set_code($coupon_code);
            $coupon->set_discount_type('percent');
            $coupon->set_amount($max_discount);
            $coupon->set_individual_use(true);
            $coupon->set_usage_limit(1); // One time use for this visitor
            $coupon->set_description(__('Generated by OrbyChat Sales AI for a visitor.', 'orbychat-sales-ai'));
            $coupon->set_date_expires(date('Y-m-d', strtotime('+24 hours'))); // Valid for 24 hours
            
            $coupon->save();
        } catch (Exception $e) {
            return new WP_Error('coupon_creation_failed', __('Could not generate a discount code at this time.', 'orbychat-sales-ai'), array('status' => 500));
        }
        
        return array(
            'status' => 'success',
            'code' => $coupon_code,
            'discount_text' => str_starts_with(get_locale(), 'tr') 
                ? sprintf('%%%d İNDİRİM', $max_discount)
                : sprintf(__('%d%% OFF', 'orbychat-sales-ai'), $max_discount),
            'instructions' => sprintf(__('Your exclusive %d%% discount code %s is ready! It is valid for the next 24 hours. Copy it and apply at checkout.', 'orbychat-sales-ai'), $max_discount, $coupon_code)
        );
    }

    public function rest_get_order($request) {
        if (!class_exists('WooCommerce')) {
            return new WP_Error('no_wc', __('WooCommerce is not active.', 'orbychat-sales-ai'), array('status' => 400));
        }

        $order = wc_get_order($request['id']);
        if (!$order) {
            return new WP_Error('not_found', __('Order not found.', 'orbychat-sales-ai'), array('status' => 404));
        }

        $items_summary = array();
        foreach ($order->get_items() as $item) {
            $items_summary[] = $item->get_name() . ' (x' . $item->get_quantity() . ')';
        }

        $status_name = wc_get_order_status_name($order->get_status());
        $summary = sprintf(
            __('Order #%s is currently %s. Total: %s %s. Items: %s', 'orbychat-sales-ai'),
            $order->get_order_number(),
            $status_name,
            $order->get_total(),
            $order->get_currency(),
            implode(', ', $items_summary)
        );

        return array(
            'order_id' => $order->get_order_number(),
            'status' => $status_name,
            'total' => $order->get_total(),
            'currency' => $order->get_currency(),
            'payment_method' => $order->get_payment_method_title(),
            'date_created' => $order->get_date_created()->date('Y-m-d H:i:s'),
            'summary' => $summary,
            'tracking_url' => $this->get_tracking_url($order)
        );
    }

    /**
     * Attempts to find a tracking URL if common tracking plugins are used.
     */
    private function get_tracking_url($order) {
        // Support for "WooCommerce Shipment Tracking" plugin
        if (function_exists('wc_st_get_tracking_number')) {
            $tracking = wc_st_get_tracking_number($order->get_id());
            if ($tracking) return $tracking;
        }

        // Support for AfterShip or similar (metadata check)
        $aftership_tracking = $order->get_meta('_aftership_tracking_number');
        if ($aftership_tracking) return 'https://www.aftership.com/track/' . $aftership_tracking;

        return '#';
    }

